/**
 * Generate src/rn/icons.generated.ts: the Ionicons SVGs the app can show.
 *
 * Mobile draws Ionicons from @expo/vector-icons (1357 glyphs; the `ionicons`
 * 8.1.0 package has an SVG for every one of them). Bundling all would add
 * ~400 KB, so this keeps every string literal in the scanned sources that is
 * an Ionicons name — over-inclusive (a literal 'add' that is not an icon
 * still gets its SVG) but never misses a computed `name={on ? 'a' : 'b'}`.
 *
 * Usage: node scripts/gen-icons.mjs [--check]
 */
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const mobileSrc = path.resolve(root, '../../mobile/app');
const svgDir = path.join(root, 'node_modules/ionicons/dist/svg');
const out = path.join(root, 'src/rn/icons.generated.ts');

// Web sources plus the mobile code the web app shares (keep in step with
// tailwind.config.js `content`).
const SCAN = [
  path.join(root, 'src'),
  path.join(mobileSrc, 'src/components'),
  path.join(mobileSrc, 'src/lib'),
  path.join(mobileSrc, 'src/modules/gloria'),
  path.join(mobileSrc, 'app/gloria'),
];

const names = new Set(readdirSync(svgDir).filter((f) => f.endsWith('.svg')).map((f) => f.slice(0, -4)));
const used = new Set();
const walk = (p) => {
  if (!existsSync(p)) return;
  if (statSync(p).isDirectory()) {
    for (const f of readdirSync(p)) walk(path.join(p, f));
    return;
  }
  if (!/\.(tsx?|mjs)$/.test(p) || p === out) return;
  for (const m of readFileSync(p, 'utf8').matchAll(/['"`]([a-z0-9]+(?:-[a-z0-9]+)*)['"`]/g)) if (names.has(m[1])) used.add(m[1]);
};
SCAN.forEach(walk);

const lines = [...used].sort().map((n) => {
  const svg = readFileSync(path.join(svgDir, `${n}.svg`), 'utf8').trim().replace(/ xmlns="http:\/\/www\.w3\.org\/2000\/svg"/, '');
  return `  ${JSON.stringify(n)}: ${JSON.stringify(svg)},`;
});
const text = `// Generated by scripts/gen-icons.mjs from ionicons 8.1.0 (MIT). Do not edit.\nexport const ICONS: Record<string, string> = {\n${lines.join('\n')}\n};\n`;

if (process.argv.includes('--check')) {
  if (!existsSync(out) || readFileSync(out, 'utf8') !== text) {
    console.error('src/rn/icons.generated.ts is stale — run: node scripts/gen-icons.mjs');
    process.exit(1);
  }
  console.log(`icons ok (${used.size})`);
} else {
  writeFileSync(out, text);
  console.log(`wrote ${used.size} icons`);
}
