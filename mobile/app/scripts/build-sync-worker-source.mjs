/**
 * Embed the sync relay's source (mobile/sync-worker/src/*.js) in the app, for
 * in-app self-hosting (src/lib/syncDeploy.ts uploads these strings).
 *
 *   node scripts/build-sync-worker-source.mjs          write src/lib/syncWorkerSource.ts
 *   node scripts/build-sync-worker-source.mjs --check  fail if it is stale
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '../../sync-worker/src');
const out = join(here, '../src/lib/syncWorkerSource.ts');
const files = ['index.js', 'quota.js'];

export function renderSource() {
  const body = files.map((f) => `  ${JSON.stringify(f)}: ${JSON.stringify(readFileSync(join(src, f), 'utf8'))},`).join('\n');
  return `/**
 * GENERATED by scripts/build-sync-worker-source.mjs — do not edit.
 * The Worker modules uploaded by in-app self-hosting; the source of truth is
 * mobile/sync-worker/src. check:team-quota fails when this file is stale.
 */
export const SYNC_WORKER_MODULES: Record<string, string> = {
${body}
};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = renderSource();
  if (process.argv.includes('--check')) {
    let cur = '';
    try {
      cur = readFileSync(out, 'utf8');
    } catch {}
    if (cur !== next) {
      console.error('src/lib/syncWorkerSource.ts is stale: run node scripts/build-sync-worker-source.mjs');
      process.exit(1);
    }
    console.log('✓ syncWorkerSource.ts up to date');
  } else {
    writeFileSync(out, next);
    console.log('wrote src/lib/syncWorkerSource.ts');
  }
}
