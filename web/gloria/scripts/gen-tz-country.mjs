#!/usr/bin/env node
/**
 * Time zone → country table for the first-run checklist suggestion
 * (src/geo/tzCountry.generated.ts), from IANA tzdata:
 *   zone.tab   one ISO 3166 country per canonical zone
 *   backward   old names → current zone (browsers may report e.g. Asia/Calcutta)
 *
 * Usage: node scripts/gen-tz-country.mjs <dir with zone.tab, backward, version>
 * Source: https://data.iana.org/time-zones/tzdata-latest.tar.gz
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node scripts/gen-tz-country.mjs <tzdata dir>');
  process.exit(2);
}
const read = (f) => readFileSync(path.join(dir, f), 'utf8');
const version = read('version').trim();

const map = new Map();
for (const line of read('zone.tab').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [cc, , zone] = line.split('\t');
  map.set(zone, cc);
}
const canonical = map.size;
// "Link TARGET LINK-NAME": the old name gets the target's country, if it has one.
for (const line of read('backward').split('\n')) {
  const m = /^Link\s+(\S+)\s+(\S+)/.exec(line);
  if (!m) continue;
  const [, target, name] = m;
  if (!map.has(name) && map.has(target)) map.set(name, map.get(target));
}

const entries = [...map.entries()].sort(([a], [b]) => a.localeCompare(b));
const out = `// Generated by scripts/gen-tz-country.mjs from IANA tzdata ${version}
// (zone.tab + backward links). Do not edit; regenerate from a newer tzdata.
// ${canonical} zones from zone.tab, ${entries.length - canonical} old names from backward.
export const TZDATA_VERSION = '${version}';
export const TZ_COUNTRY: Record<string, string> = {
${entries.map(([z, c]) => `  '${z}': '${c}',`).join('\n')}
};
`;
const target = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/geo/tzCountry.generated.ts');
writeFileSync(target, out);
console.log(`wrote ${entries.length} zones (${canonical} canonical) from tzdata ${version}`);
